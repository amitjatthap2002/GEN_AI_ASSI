"""### Lab 1 Explanation: Variational Autoencoders (VAEs)

#### How it Works:
Unlike standard Autoencoders that map inputs to a single fixed vector in the latent space, a **Variational Autoencoder (VAE)** maps inputs to a probability distribution (defined by a mean $\mu$ and log-variance $\log(\sigma^2)$).

1. **Encoder**: Projects the input MNIST image ($28 \times 28 = 784$ pixels) down to a hidden state of $256$ dimensions, and then outputs two vectors of size $2$ (representing the 2D latent space parameters: $\mu$ and $\log\sigma^2$).
2. **Reparameterization Trick**: To allow backpropagation through stochastic sampling, we compute:
   $$z = \mu + e^{0.5 \cdot \log\sigma^2} \odot \epsilon$$
   where $\epsilon \sim \mathcal{N}(0, I)$.
3. **Decoder**: Maps the sample $z \in \mathbb{R}^2$ back to a $784$-dimensional reconstruction, utilizing a Sigmoid activation to match the normalized pixel scale $[0, 1]$.
4. **Loss Function**: Consists of two components:
   - **Reconstruction Loss**: Binary Cross Entropy (BCE) measuring how closely the decoded image matches the original input.
   - **KL Divergence**: Restricts the latent distribution from shifting too far from a standard normal prior $\mathcal{N}(0, I)$, ensuring smooth interpolation and generation.

#### Output Assessment:
* **vae_reconstructed.png**: Shows matching input digits alongside their smooth, occasionally blurry reconstructions.
* **vae_generated.png**: Digit images synthesized by passing random coordinates from the normal prior directly to the decoder.
* **vae_latent.png**: A scatter plot of the test set projected onto the 2D latent space, showing colored groupings representing digit classes.
"""

