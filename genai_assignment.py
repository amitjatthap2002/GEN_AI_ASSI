"""### Lab 2 Explanation: Generative Adversarial Networks (GANs)

#### How it Works:
**Generative Adversarial Networks (GANs)** frame image generation as a min-max game between two competing neural networks:

1. **Generator ($G$)**: Learns to capture the true data distribution. It maps a random noise vector $z \in \mathbb{R}^{64}$ through dense layers with LeakyReLU activations and outputs a $784$-dimensional vector. A $Tanh$ activation scales the output pixels to $[-1, 1]$.
2. **Discriminator ($D$)**: A binary classifier that estimates the probability that a sample came from the real dataset rather than $G$. It maps a flattened image to a single logit.

#### Alternating Updates:
- **Discriminator Step**: Evaluated on real images (target label: 1) and fake images (target label: 0). The gradients are computed and backpropagated only through $D$'s weights.
- **Generator Step**: Generates fresh fake images, feeds them to the discriminator, and calculates the loss using real targets (1). During this stage, the gradients pass through $D$ to update $G$, but $D$'s parameters are explicitly frozen (`D.requires_grad_(False)`).

#### Convergence Indicators:
- As training proceeds, $G$'s outputs transform from random salt-and-pepper noise to structured clothing shapes (Fashion-MNIST).
- Adversarial balance is visible when discriminator and generator losses stabilize or oscillate together instead of one dropping to zero.
"""

