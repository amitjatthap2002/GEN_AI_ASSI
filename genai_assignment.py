"""### Lab 3 Explanation: Text Generation & Fine-Tuning with GPT-2

#### How it Works:
**GPT-2** is an autoregressive Transformer decoder model designed to predict the probability distribution of the next token given a sequence of preceding tokens.

1. **Decoding Strategies (Inference)**:
   - **Greedy Decoding**: Always selects the token with the highest probability. While coherent, it often results in repetitive, deterministic loops.
   - **Temperature Sampling**: Controls the randomness of prediction probabilities. A lower temperature (e.g., $0.6$) concentrates probability mass around confident tokens, generating safe text. A higher temperature (e.g., $1.0$) flattens the distribution, encouraging creative but riskier generation.

2. **Parameter-Efficient Fine-Tuning (PEFT)**:
   - To adapt GPT-2 into a "Study Tip Generator", we freeze the entire base model except for the last Transformer block (`tuned.transformer.h[-1]`). This drastically reduces the parameter footprint and accelerates training.
   - **Prefix Labeling**: During loss calculation, we set labels for the prefix sequence (`Topic: {topic}\nStudy tip:`) to `-100`. PyTorch's cross-entropy loss automatically ignores these positions, training the model to optimize only the generated response tokens.
"""

