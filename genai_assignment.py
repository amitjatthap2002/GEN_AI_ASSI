"""### Lab 4 Explanation: Multimodal Prompt-to-Image Generation

#### How it Works:
**Stable Diffusion** is a latent text-to-image diffusion model that generates high-resolution images by operating inside a compressed latent space rather than pixel space.

1. **Pipeline Components**:
   - **Text Encoder (CLIP)**: Translates the raw text prompt (e.g., "pencil sketch" vs "watercolor") into dense vector embeddings.
   - **U-Net**: Iteratively predicts and removes noise from latent representations starting from purely random Gaussian noise, guided by the text embeddings.
   - **Variational Autoencoder (VAE)**: Decodes the final cleaned latent representation back into a full-scale $512 \times 512$ RGB image.

2. **Controlled Evaluation**:
   - By using a fixed generator seed (`torch.Generator(device=device).manual_seed(seed)`), we keep the initial starting noise identical across prompt comparisons. This isolates the effect of changes in prompt phrasing (watercolor vs. pencil sketch) from structural shifts caused by random initialization variations.
"""